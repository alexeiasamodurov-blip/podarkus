import { readFile, writeFile, mkdir } from 'node:fs/promises';
const html = await readFile('index.html', 'utf8');
const json = html.match(/<script type="application\/json" id="podarkus-data">([\s\S]*?)<\/script>/)[1];
const app = html.match(/<script>([\s\S]*?)<\/script>/)[1];
let engine = app.slice(0, app.indexOf('\nconst localCatalogue='));
if (!engine.includes('items:ranked.slice(0,6)')) throw Error('Matcher changed: review extraction before publishing');
// AI considers a wider range of interests; every hard exclusion stays in this matcher.
engine = engine.replace('function createPodarkusLocal(data)', 'export function createPodarkusLocal(data, aiCandidates = false)');
engine = engine.replace('if (positive.size && !matched.length) continue;', 'if (!aiCandidates && positive.size && !matched.length) continue;');
engine = engine.replace("if (!positive.size && !tags.includes('general') && !occasions.includes(a.occasion_group)) continue;", "if (!aiCandidates && !positive.size && !tags.includes('general') && !occasions.includes(a.occasion_group)) continue;");
engine = engine.replace('items:ranked.slice(0,6)', 'items:ranked.slice(0,aiCandidates ? 500 : 6)');
await mkdir('worker', { recursive: true });
await writeFile('worker/catalog.json', json);
await writeFile('worker/catalog-engine.js', '// Generated by scripts/extract-ai-catalog.mjs; preserve the HTML matcher.\n' + engine);
console.log('Extracted catalogue:', JSON.parse(json).gifts.length, 'ideas');
